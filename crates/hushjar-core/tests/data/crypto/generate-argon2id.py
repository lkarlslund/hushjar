"""Append independent libargon2 vectors; retain the upstream literal first vector."""
import ctypes
import hashlib
import json
from pathlib import Path

root = Path(__file__).parent
lib = ctypes.CDLL('libargon2.so.1')
derive = lib.argon2id_hash_raw
derive.argtypes = [ctypes.c_uint32] * 3 + [ctypes.c_void_p, ctypes.c_size_t] * 3
derive.restype = ctypes.c_int
vectors = json.loads((root / 'argon2id.json').read_text())[:1]
for iterations, memory, lanes in [(2, 16, 1), (6, 32, 4), (2, 17, 3)]:
    email, password = 'test_key', 'synthetic\0 password '
    secret = password.encode('utf8')
    salt = hashlib.sha256(email.encode('utf8')).digest()
    output = ctypes.create_string_buffer(32)
    status = derive(iterations, memory * 1024, lanes, secret, len(secret), salt, len(salt), output, 32)
    if status != 0:
        raise RuntimeError(f'libargon2 failed: {status}')
    vectors.append(dict(email=email, password=password, iterations=iterations, memory_mib=memory,
                        parallelism=lanes, key_hex=output.raw.hex()))
raw = json.dumps(vectors, indent=2) + '\n'
(root / 'argon2id.json').write_text(raw)
manifest_path = root / 'argon2id.manifest.json'
manifest = json.loads(manifest_path.read_text())
manifest['sha256'] = hashlib.sha256(raw.encode()).hexdigest()
manifest['generation'] = ('First vector transcribed from pinned SDK test_master_key_derive_argon2. '
                         'Additional vectors generated by generate-argon2id.py using independent '
                         'libargon2.so.1, Arch argon2 20190702-6.3; includes non-divisible memory/lane '
                         'geometry and a NUL/whitespace password. No VaultGoblin-derived expectations.')
manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
